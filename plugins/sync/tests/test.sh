#!/bin/sh
# Tests for guard.sh and sync.sh against a fake home: `plugins/sync/tests/test.sh`.
set -eu
scripts=$(cd "$(dirname "$0")/../scripts" && pwd)
home=$(mktemp -d "${TMPDIR:-/tmp}/sync-test.XXXX")
trap 'rm -rf "$home"' EXIT
export HOME="$home"
unset CLAUDE_CONFIG_DIR
failures=0

plugins="$home/.claude/plugins"
clone="$plugins/marketplaces/vlad-skills"
mkdir -p "$clone/.claude-plugin" "$clone/agents" "$plugins/marketplaces/other" \
  "$plugins/cache/vlad-skills/ship/abc123/skills/start" "$plugins/cache/vlad-skills/ext/1.0" "$home/.codex" \
  "$home/git/skills"
cat > "$plugins/known_marketplaces.json" <<JSON
{
  "vlad-skills": {"source": {"source": "github", "repo": "vladsavelyev/skills"}, "installLocation": "$clone"},
  "other": {"source": {"source": "git", "url": "https://example.com/other.git"},
            "installLocation": "$plugins/marketplaces/other"}
}
JSON
cat > "$clone/.claude-plugin/marketplace.json" <<'JSON'
{"plugins": [{"name": "ship", "source": "./plugins/ship"}, {"name": "ext", "source": {"source": "url", "url": "x"}}]}
JSON
echo rules > "$clone/agents/AGENTS.md"
git -C "$clone" init -q
git -C "$clone" add -A
git -C "$clone" -c user.name=t -c user.email=t commit -qm init
ln -s "$clone/agents" "$home/linked-agents"

check() { # <name> <file path> <expected substring of the reason, or "allow">
  out=$(jq -n --arg p "$2" '{tool_name: "Edit", tool_input: {file_path: $p}}' | "$scripts/guard.sh")
  reason=$(printf '%s' "$out" | jq -r 'select(.hookSpecificOutput.permissionDecision == "deny")
    | .hookSpecificOutput.permissionDecisionReason')
  if [ "$3" = allow ]; then
    [ -z "$out" ] && return 0
  else
    case $reason in *"$3"*) return 0 ;; esac
  fi
  echo "FAIL $1: expected $3, got: ${out:-nothing}"
  failures=$((failures + 1))
}

check "shared rules" "$clone/agents/AGENTS.md" "in agents/AGENTS.md, on a branch with a PR"
check "shared rules say where machine rules go" "$clone/agents/AGENTS.md" "below the fleet"
check "shared rules through a symlink" "$home/linked-agents/AGENTS.md" "in agents/AGENTS.md"
check "new file in a new directory" "$clone/plugins/new/x.md" "in plugins/new/x.md"
check "cached plugin maps to its directory" "$plugins/cache/vlad-skills/ship/abc123/skills/start/SKILL.md" \
  "in plugins/ship/skills/start/SKILL.md"
check "cached plugin from elsewhere" "$plugins/cache/vlad-skills/ext/1.0/x" "the plugin's own source repo"
check "another marketplace" "$plugins/marketplaces/other/README.md" "https://example.com/other.git, in README.md"
check "codex rules" "$home/.codex/AGENTS.md" "generated by \`fleet --apply\`"
check "the repo checkout" "$home/git/skills/agents/AGENTS.md" allow
check "CLAUDE.md" "$home/.claude/CLAUDE.md" allow
check "codex config" "$home/.codex/config.toml" allow
out=$(echo '{"tool_name": "Write", "tool_input": {}}' | "$scripts/guard.sh")
[ -z "$out" ] || { echo "FAIL no path: got $out"; failures=$((failures + 1)); }

# sync.sh stops at a modified clone, before it calls `claude` (a stub that records the call).
mkdir "$home/bin"
printf '#!/bin/sh\necho called >> "%s/claude-called"\nexit 1\n' "$home" > "$home/bin/claude"
chmod +x "$home/bin/claude"
echo edited >> "$clone/agents/AGENTS.md"
out=$(PATH="$home/bin:$PATH" "$scripts/sync.sh" "$home/data")
sleep 1
[ ! -e "$home/claude-called" ] || { echo "FAIL sync.sh updated a modified clone"; failures=$((failures + 1)); }
case $out in
  *"was not updated"*"M agents/AGENTS.md"*"on a branch with a PR"*) ;;
  *) echo "FAIL sync.sh with a modified clone: $out"; failures=$((failures + 1)) ;;
esac

[ "$failures" = 0 ] && echo "all passed" || { echo "$failures failed"; exit 1; }
